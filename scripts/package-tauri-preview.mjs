import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { cp, mkdir, readFile, stat, symlink, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const exec=promisify(execFile);
const root=fileURLToPath(new URL('../',import.meta.url));
if(process.platform!=='darwin') throw new Error('Tauri preview packaging requires macOS.');
const packageInfo=JSON.parse(await readFile(path.join(root,'package.json'),'utf8'));
const revision=(await exec('git',['rev-parse','--short','HEAD'],{cwd:root})).stdout.trim();
const dirty=Boolean((await exec('git',['status','--porcelain'],{cwd:root})).stdout.trim());
const stamp=new Date().toISOString().replace(/[-:TZ.]/g,'').slice(0,14);
const version=packageInfo.version;
if(!version.includes('-')) throw new Error('Preview builds require a prerelease version.');
const buildId=`${stamp}.${revision}${dirty?'.dirty':''}`;
const name=`BytePet-Tauri-${version}-${process.arch}`;
const output=path.join(root,'dist/tauri-preview',`${name}-${buildId}`);
await mkdir(output,{recursive:true});
// --skip-build is useful only when tauri:build has just completed for this tree.
if(!process.argv.includes('--skip-build')) await exec('npm',['run','tauri:build'],{cwd:root,maxBuffer:8*1024*1024});
const source=path.join(root,'src-tauri/target/release/bundle/macos/BytePet Tauri Preview.app');
const app=path.join(output,'BytePet Tauri Preview.app');
await cp(source,app,{recursive:true});
await exec('/usr/bin/codesign',['--verify','--deep','--strict',app]);
const stage=path.join(root,'build',`${name}-${buildId}`);await mkdir(stage,{recursive:true});
await cp(app,path.join(stage,path.basename(app)),{recursive:true});
await symlink('/Applications',path.join(stage,'Applications'));
const dmg=path.join(output,`${name}.dmg`);
await exec('/usr/bin/hdiutil',['create','-volname','BytePet Tauri Preview','-srcfolder',stage,'-ov','-format','ULMO',dmg],{maxBuffer:1024*1024});
await exec('/usr/bin/hdiutil',['verify',dmg],{maxBuffer:1024*1024});
const bytes=(await stat(dmg)).size;
const metadata={runtime:'Tauri',version,buildId,revision,dirty,arch:process.arch,builtAt:new Date().toISOString(),dmg:path.basename(dmg),dmgBytes:bytes,codeSigning:'ad-hoc',notarized:false};
await writeFile(path.join(output,'build-info.json'),JSON.stringify(metadata,null,2)+'\n');
const checksum=(await exec('/usr/bin/shasum',['-a','256',dmg])).stdout.split(' ')[0];
await writeFile(path.join(output,'SHA256SUMS.txt'),`${checksum}  ${path.basename(dmg)}\n`);
const target=(await exec('git',['rev-parse','HEAD'],{cwd:root})).stdout.trim();
const notes=await readFile(path.join(root,'docs/releases',`v${version}.md`),'utf8');
await writeFile(path.join(output,'RELEASE_NOTES.md'),notes);
await writeFile(path.join(output,'release-settings.json'),JSON.stringify({tag_name:`v${version}`,target_commitish:target,name:`BytePet v${version} · Tauri 미리보기`,draft:false,prerelease:true,make_latest:'false'},null,2)+'\n');
console.log(JSON.stringify({app,dmg,dmgMiB:Number((bytes/1024/1024).toFixed(2))},null,2));
