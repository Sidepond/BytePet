import { copyFile, mkdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const pack = JSON.parse(await readFile(path.join(root, 'art/pixellab-character-pack/manifest.json'), 'utf8'));
const manifest = {};
for (const character of pack.characters) {
  const source = path.resolve(root, 'art/pixellab-character-pack', character.directory);
  const atlas = JSON.parse(await readFile(path.join(source, 'atlas.json'), 'utf8'));
  if (atlas.frame.width !== 96 || atlas.frame.height !== 96 || atlas.columns !== 4 || atlas.rows !== 2 || atlas.frames !== 8) {
    throw new Error(`Unsupported sprite layout: ${atlas.character}`);
  }
  const target = path.join(root, 'desktop/assets/characters', atlas.catalogId);
  await mkdir(target, { recursive: true });
  const actions = {};
  for (const action of Object.keys(atlas.actions)) {
    const { file, durationMs } = atlas.actions[action];
    const bytes = await readFile(path.join(source, file));
    if (bytes.readUInt32BE(16) !== 384 || bytes.readUInt32BE(20) !== 192 || durationMs.length !== 8 || durationMs.some(ms => !Number.isFinite(ms) || ms <= 0)) {
      throw new Error(`Invalid sprite: ${atlas.character}/${action}`);
    }
    await copyFile(path.join(source, file), path.join(target, `${action}.png`));
    actions[action] = { file: `./assets/characters/${atlas.catalogId}/${action}.png`, durationMs };
  }
  manifest[atlas.catalogId] = { name: atlas.name, kind: atlas.kind, actions };
}
await writeFile(path.join(root, 'desktop/sprite-manifest.js'), `// Generated by npm run sync:characters from the approved PixelLab atlases.\nexport default ${JSON.stringify(manifest, null, 2)};\n`);
console.log(`Synced ${Object.keys(manifest).length} characters (${Object.values(manifest).reduce((count, pet) => count + Object.keys(pet.actions).length, 0)} sprite sheets).`);
